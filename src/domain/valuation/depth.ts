export function depthCorrection(district: District, depthM: number): number {
  if (!(depthM > 0)) throw new Error("奥行距離は正の数で入力してください");
  const col = DISTRICTS.indexOf(district) + 1;
  let row = TABLE[0];
  for (const r of TABLE) if (depthM >= r[0]) row = r;
  return row[col];
}
